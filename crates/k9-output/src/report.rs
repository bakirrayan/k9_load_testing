const LOGO: &[u8] = include_bytes!("../assets/logo-96.png");

// The logo's colours, plus status colours.
const GOLD: &str = "#D19E4B";
const BLUE: &str = "#0B6BE7";
const RED: &str = "#E5484D";
const GREY: &str = "#8B8B8B";

/// What the report says about the run beyond its metrics.
pub struct ReportInfo<'a> {
    pub header: &'a RunHeader,
    pub started: SystemTime,
    /// Aggregation ticks (one a second), for the charts.
    pub ticks: &'a [Tick],
}

pub fn html_report(data: &SummaryData<'_>, info: &ReportInfo<'_>) -> String {
    let passed = data.thresholds.iter().all(|t| t.passed);
    let mut html = String::with_capacity(64 * 1024);
    let title = format!("K9 report: {}", info.header.script);
    let _ = write!(
        html,
        "<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n\
         <title>{}</title>\n<style>{STYLE}</style>\n</head>\n<body>\n<main>\n",
        esc(&title)
    );
    header(&mut html, data, info, passed);
    cards(&mut html, data);
    thresholds(&mut html, data);
    checks(&mut html, data);
    charts(&mut html, data, info.ticks);
    metrics(&mut html, data);
    let _ = write!(
        html,
        "<footer>Generated by k9 {} at {}</footer>\n</main>\n</body>\n</html>\n",
        env!("CARGO_PKG_VERSION"),
        esc(&when(SystemTime::now()))
    );
    html
}

fn header(html: &mut String, data: &SummaryData<'_>, info: &ReportInfo<'_>, passed: bool) {
    let (badge, class) = if data.thresholds.is_empty() {
        ("Finished", "neutral")
    } else if passed {
        ("Thresholds passed", "pass")
    } else {
        ("Thresholds crossed", "fail")
    };
    let _ = writeln!(
        html,
        "<header><img class=\"logo\" alt=\"K9\" width=\"48\" height=\"48\" src=\"data:image/png;base64,{}\">\
         <div><h1>{}</h1><p class=\"muted\"><code>{}</code><br>Started {} · ran for {}</p></div>\
         <span class=\"badge {class}\">{badge}</span></header>",
        base64(LOGO),
        esc(file_name(&info.header.script)),
        esc(&info.header.script),
        esc(&when(info.started)),
        esc(&format::duration_ms(data.duration.as_secs_f64() * 1e3)),
    );
    html.push_str("<section><h2>Scenarios</h2><ul class=\"scenarios\">");
    for s in &info.header.scenarios {
        let _ = write!(
            html,
            "<li><strong>{}</strong>: {}</li>",
            esc(&s.name),
            esc(&s.description)
        );
    }
    html.push_str("</ul>");
    if let Some(workers) = info.header.workers {
        let _ = write!(
            html,
            "<p class=\"muted\">Across {workers} worker processes.</p>"
        );
    }
    html.push_str("</section>\n");
}

/// The totals of `name`, merged across tag sets.
fn total(data: &SummaryData<'_>, name: &str) -> Option<Value> {
    let id = data.registry.get(name)?;
    data.totals.merged(id, &[], data.interner)
}

fn cards(html: &mut String, data: &SummaryData<'_>) {
    let secs = data.duration.as_secs_f64().max(f64::MIN_POSITIVE);
    let mut cards: Vec<(String, String)> = Vec::new();
    if let Some(Value::Counter(c)) = total(data, "http_reqs") {
        cards.push(("Requests".into(), format::number(c.sum)));
        cards.push(("Requests/s".into(), short(c.sum / secs)));
    }
    if let Some(Value::Rate(r)) = total(data, "http_req_failed") {
        cards.push(("Failed requests".into(), format::percent(r.rate())));
    }
    if let Some(Value::Trend(t)) = total(data, "http_req_duration") {
        cards.push((
            "Response time p(95)".into(),
            format::duration_ms(t.percentile(95.0)),
        ));
    }
    if let Some(Value::Counter(c)) = total(data, "iterations") {
        cards.push(("Iterations".into(), format::number(c.sum)));
    }
    if let Some(Value::Rate(r)) = total(data, "checks") {
        cards.push(("Checks passed".into(), format::percent(r.rate())));
    }
    if let Some(Value::Gauge(g)) = total(data, "vus_max") {
        cards.push(("Max VUs".into(), format::number(g.value)));
    }
    html.push_str("<section class=\"cards\">");
    for (label, value) in cards {
        let _ = write!(
            html,
            "<div class=\"card\"><div class=\"value\">{}</div><div class=\"muted\">{}</div></div>",
            esc(&value),
            esc(&label)
        );
    }
    html.push_str("</section>\n");
}

fn thresholds(html: &mut String, data: &SummaryData<'_>) {
    if data.thresholds.is_empty() {
        return;
    }
    html.push_str(
        "<section><h2>Thresholds</h2><table><thead><tr><th></th><th>Metric</th>\
         <th>Threshold</th></tr></thead><tbody>",
    );
    for t in &data.thresholds {
        let metric = if t.tags.is_empty() {
            t.metric.clone()
        } else {
            let tags: Vec<String> = t.tags.iter().map(|(k, v)| format!("{k}:{v}")).collect();
            format!("{}{{{}}}", t.metric, tags.join(","))
        };
        let (mark, class) = if t.passed {
            ("✓", "pass")
        } else {
            ("✗", "fail")
        };
        let _ = write!(
            html,
            "<tr><td class=\"{class}\">{mark}</td><td><code>{}</code></td><td><code>{}</code></td></tr>",
            esc(&metric),
            esc(&t.expression)
        );
    }
    html.push_str("</tbody></table></section>\n");
}

fn checks(html: &mut String, data: &SummaryData<'_>) {
    let groups = check_groups(data);
    if groups.values().all(|checks| checks.is_empty()) {
        return;
    }
    html.push_str(
        "<section><h2>Checks</h2><table><thead><tr><th></th><th>Group</th><th>Check</th>\
         <th class=\"num\">Passed</th><th class=\"num\">Failed</th></tr></thead><tbody>",
    );
    for (group, checks) in &groups {
        for (name, (passes, total)) in checks {
            let fails = total - passes;
            let (mark, class) = if fails == 0 {
                ("✓", "pass")
            } else {
                ("✗", "fail")
            };
            let group = if group.is_empty() { "–" } else { group };
            let _ = write!(
                html,
                "<tr><td class=\"{class}\">{mark}</td><td><code>{}</code></td><td>{}</td>\
                 <td class=\"num\">{passes}</td><td class=\"num\">{fails}</td></tr>",
                esc(group),
                esc(name)
            );
        }
    }
    html.push_str("</tbody></table></section>\n");
}

/// One chart's line: a name, a colour and (seconds, value) points.
struct Line {
    name: &'static str,
    color: &'static str,
    points: Vec<(f64, f64)>,
}

fn charts(html: &mut String, data: &SummaryData<'_>, ticks: &[Tick]) {
    let id = |name: &str| data.registry.get(name);
    let mut previous = 0.0;
    // (seconds since start, seconds since the previous tick, tick)
    let times: Vec<(f64, f64, &Tick)> = ticks
        .iter()
        .map(|tick| {
            let at = tick.elapsed.as_secs_f64();
            let span = (at - previous).max(1e-3);
            previous = at;
            (at, span, tick)
        })
        .collect();
    let series = |metric: Option<MetricId>, value: &dyn Fn(&Stats, f64) -> Option<f64>| {
        times
            .iter()
            .filter_map(|(at, span, tick)| {
                let stats = tick.metrics.get(&metric?)?;
                Some((*at, value(stats, *span)?))
            })
            .collect::<Vec<_>>()
    };
    let per_second = |stats: &Stats, span: f64| match stats {
        Stats::Counter { sum } => Some(sum / span),
        _ => None,
    };
    let trend = |pick: fn(&Stats) -> Option<f64>| move |stats: &Stats, _: f64| pick(stats);

    html.push_str("<section><h2>Over time</h2><div class=\"charts\">");
    chart(
        html,
        "Virtual users",
        &format::number,
        vec![Line {
            name: "VUs",
            color: BLUE,
            points: series(id("vus"), &|s, _| match s {
                Stats::Gauge { value } => Some(*value),
                _ => None,
            }),
        }],
    );
    chart(
        html,
        "Requests per second",
        &format::number,
        vec![
            Line {
                name: "all",
                color: BLUE,
                points: series(id("http_reqs"), &per_second),
            },
            Line {
                name: "failed",
                color: RED,
                points: series(id("http_req_failed"), &|s, span| match s {
                    Stats::Rate { trues, .. } => Some(*trues as f64 / span),
                    _ => None,
                }),
            },
        ],
    );
    let duration = id("http_req_duration");
    chart(
        html,
        "Response time (http_req_duration)",
        &format::duration_ms,
        vec![
            Line {
                name: "avg",
                color: GREY,
                points: series(
                    duration,
                    &trend(|s| match s {
                        Stats::Trend { avg, .. } => Some(*avg),
                        _ => None,
                    }),
                ),
            },
            Line {
                name: "p(95)",
                color: BLUE,
                points: series(
                    duration,
                    &trend(|s| match s {
                        Stats::Trend { p95, .. } => Some(*p95),
                        _ => None,
                    }),
                ),
            },
            Line {
                name: "p(99)",
                color: GOLD,
                points: series(
                    duration,
                    &trend(|s| match s {
                        Stats::Trend { p99, .. } => Some(*p99),
                        _ => None,
                    }),
                ),
            },
        ],
    );
    chart(
        html,
        "Iterations per second",
        &format::number,
        vec![Line {
            name: "iterations",
            color: GOLD,
            points: series(id("iterations"), &per_second),
        }],
    );
    html.push_str("</div></section>\n");
}

fn chart(html: &mut String, title: &str, fmt: &dyn Fn(f64) -> String, lines: Vec<Line>) {
    const W: f64 = 480.0;
    const H: f64 = 220.0;
    const LEFT: f64 = 64.0;
    const RIGHT: f64 = 12.0;
    const TOP: f64 = 10.0;
    const BOTTOM: f64 = 24.0;
    let points = lines.iter().flat_map(|l| &l.points);
    let max_x = points.clone().map(|p| p.0).fold(0.0, f64::max).max(1.0);
    let max_y = nice_ceiling(points.map(|p| p.1).fold(0.0, f64::max));
    let x = |v: f64| LEFT + v / max_x * (W - LEFT - RIGHT);
    let y = |v: f64| H - BOTTOM - v / max_y * (H - TOP - BOTTOM);
    let _ = write!(
        html,
        "<figure><figcaption>{}<span class=\"legend\">",
        esc(title)
    );
    for line in &lines {
        let _ = write!(
            html,
            "<span><i style=\"background:{}\"></i>{}</span>",
            line.color,
            esc(line.name)
        );
    }
    let _ = write!(
        html,
        "</span></figcaption><svg viewBox=\"0 0 {W} {H}\" role=\"img\" aria-label=\"{}\">",
        esc(title)
    );
    for i in 0..=4 {
        let v = max_y * f64::from(i) / 4.0;
        let _ = write!(
            html,
            "<line class=\"grid\" x1=\"{LEFT}\" x2=\"{}\" y1=\"{y:.1}\" y2=\"{y:.1}\"/>\
             <text class=\"axis\" x=\"{}\" y=\"{:.1}\" text-anchor=\"end\">{}</text>",
            W - RIGHT,
            LEFT - 6.0,
            y(v) + 4.0,
            esc(&fmt(v)),
            y = y(v),
        );
    }
    for (v, anchor) in [(0.0, "start"), (max_x / 2.0, "middle"), (max_x, "end")] {
        let _ = write!(
            html,
            "<text class=\"axis\" x=\"{:.1}\" y=\"{}\" text-anchor=\"{anchor}\">{}</text>",
            x(v),
            H - 6.0,
            esc(&format::duration_ms(v * 1e3))
        );
    }
    if lines.iter().all(|l| l.points.is_empty()) {
        let _ = write!(
            html,
            "<text class=\"axis\" x=\"{}\" y=\"{}\" text-anchor=\"middle\">no data</text>",
            W / 2.0,
            H / 2.0
        );
    }
    for line in &lines {
        let coords: Vec<String> = line
            .points
            .iter()
            .map(|(px, py)| format!("{:.1},{:.1}", x(*px), y(*py)))
            .collect();
        let _ = write!(
            html,
            "<polyline fill=\"none\" stroke=\"{}\" stroke-width=\"2\" points=\"{}\"/>",
            line.color,
            coords.join(" ")
        );
    }
    html.push_str("</svg></figure>");
}

/// The smallest 1, 2 or 5 × 10ⁿ at or above `v` (1 for nothing).
fn nice_ceiling(v: f64) -> f64 {
    if v.is_nan() || v <= 0.0 {
        return 1.0;
    }
    let magnitude = 10f64.powf(v.log10().floor());
    [1.0, 2.0, 5.0, 10.0]
        .iter()
        .map(|m| m * magnitude)
        .find(|c| *c >= v)
        .unwrap_or(10.0 * magnitude)
}

fn metrics(html: &mut String, data: &SummaryData<'_>) {
    let export = summary_export(data);
    let Some(Json::Object(metrics)) = export.get("metrics") else {
        return;
    };
    html.push_str(
        "<section><h2>Metrics</h2><table><thead><tr><th>Metric</th><th>Values</th></tr>\
         </thead><tbody>",
    );
    for (name, values) in metrics {
        let base = name.split('{').next().unwrap_or(name);
        let value_type = data
            .registry
            .get(base)
            .map_or(ValueType::Default, |id| data.registry.def(id).value_type);
        let is_rate = data
            .registry
            .get(base)
            .is_some_and(|id| data.registry.def(id).kind == k9_metrics::MetricKind::Rate);
        let Json::Object(values) = values else {
            continue;
        };
        let cells: Vec<String> = values
            .iter()
            .filter(|(k, _)| *k != "thresholds")
            .filter_map(|(k, v)| {
                let v = v.as_f64()?;
                let shown = match (k.as_str(), value_type) {
                    ("passes" | "fails" | "count", _) if !is_rate || k != "count" => {
                        format::number(v)
                    }
                    ("value", _) if is_rate => format::percent(v),
                    ("rate", _) => format!("{}/s", short(v)),
                    (_, ValueType::Time) => format::duration_ms(v),
                    (_, ValueType::Data) => format::bytes(v),
                    _ => format::number(v),
                };
                Some(format!(
                    "<span class=\"kv\">{}=<b>{}</b></span>",
                    esc(k),
                    esc(&shown)
                ))
            })
            .collect();
        let _ = write!(
            html,
            "<tr><td><code>{}</code></td><td>{}</td></tr>",
            esc(name),
            cells.join(" ")
        );
    }
    html.push_str("</tbody></table></section>\n");
}

/// `/path/to/test.py` → `test.py`.
fn file_name(path: &str) -> &str {
    path.rsplit(['/', '\\']).next().unwrap_or(path)
}

/// `2026-09-30 00:00:34 UTC`.
fn when(time: SystemTime) -> String {
    let stamp = format::rfc3339(time);
    let seconds = stamp
        .split('.')
        .next()
        .unwrap_or(&stamp)
        .trim_end_matches('Z');
    format!("{} UTC", seconds.replacen('T', " ", 1))
}

/// A rate for people: 195.2, 24202, 0.83.
fn short(v: f64) -> String {
    if v.abs() >= 100.0 {
        format!("{v:.0}")
    } else if v.abs() >= 10.0 {
        format!("{v:.1}")
    } else {
        format!("{v:.2}")
    }
}

fn esc(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            c => out.push(c),
        }
    }
    out
}

pub(crate) fn base64(bytes: &[u8]) -> String {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for chunk in bytes.chunks(3) {
        let n = chunk.iter().fold(0u32, |n, b| n << 8 | u32::from(*b)) << (8 * (3 - chunk.len()));
        for i in 0..4 {
            if i <= chunk.len() {
                out.push(ALPHABET[(n >> (18 - 6 * i) & 63) as usize] as char);
            } else {
                out.push('=');
            }
        }
    }
    out
}

